import { readFile } from 'node:fs/promises'
import { expect, test } from '@playwright/test'
const base = process.env.TWINTAIL_WEB_BASE_URL
const tokenFile = process.env.TWINTAIL_WEB_TOKEN_FILE
test('live host: login, schema validation, configuration CAS, stop/start/reload, diagnostics', async ({ page }, info) => {
  test.skip(!base || !tokenFile, 'Requires an isolated live host and protected token file')
  test.setTimeout(90_000)
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto(base!)
  await page.getByLabel('管理令牌', { exact: true }).fill((await readFile(tokenFile!, 'utf8')).trim())
  await page.getByRole('button', { name: '进入控制台 →' }).click()
  await expect(page.getByRole('heading', { name: '运行概览', exact: true })).toBeVisible()
  await expect(page.getByText('只读模式', { exact: true })).toBeHidden({ timeout: 25_000 })
  await page.getByRole('button', { name: /echo-plugin.*查看详情与配置/ }).click()
  const editor = page.getByRole('textbox', { name: 'JSON 配置编辑器' })
  await expect(editor).toBeVisible()
  await page.screenshot({ path: `/tmp/twintail-p5-live-${info.project.name}-config.png`, fullPage: true })
  const original = await editor.inputValue()
  // Whitespace changes submit the same semantic configuration, without fixture-specific fields.
  await editor.fill(`${original}\n`)
  await page.getByRole('button', { name: '校验配置', exact: true }).click()
  await expect(page.locator('.detail-panel [role="status"]')).toContainText('配置校验通过')
  await page.getByRole('button', { name: '保存并应用', exact: true }).click()
  await page.getByRole('button', { name: '确认操作', exact: true }).click()
  // echo-plugin does not implement the two-phase configuration protocol.
  await expect(page.locator('.detail-panel [role="alert"]')).toContainText('配置更新失败（unsupported）', { timeout: 20_000 })
  await expect(editor).toHaveValue(`${original}\n`)
  await page.getByRole('button', { name: '重新读取配置', exact: true }).click()
  await page.getByRole('button', { name: '确认操作', exact: true }).click()
  await expect(page.locator('.config-layout label')).toContainText('编辑基于修订')
  await page.getByRole('button', { name: '停止', exact: true }).click()
  await page.getByRole('button', { name: '确认操作', exact: true }).click()
  await expect(page.locator('.detail-panel .panel-heading')).toContainText('已停止', { timeout: 20_000 })
  const oldRevision = Number(await page.locator('.revision-bar strong').first().textContent())
  const offline = await editor.inputValue()
  await editor.fill(`${offline}\n`)
  await page.getByRole('button', { name: '保存并应用', exact: true }).click()
  await page.getByRole('button', { name: '确认操作', exact: true }).click()
  await expect(page.locator('.detail-panel [role="status"]')).toContainText('配置操作已完成', { timeout: 20_000 })
  await expect(editor).toHaveValue(`${offline}\n`)
  await page.getByRole('button', { name: '重新读取配置', exact: true }).click()
  await page.getByRole('button', { name: '确认操作', exact: true }).click()
  await expect(page.locator('.config-layout label')).toContainText(`编辑基于修订 ${oldRevision + 1}`)
  for (const action of ['启动', '重载此版本']) {
    const before = Number((await page.locator('.detail-panel .panel-heading').textContent())?.match(/代次 (\d+)/)?.[1])
    await page.getByRole('button', { name: action, exact: true }).click()
    await page.getByRole('button', { name: '确认操作', exact: true }).click()
    await expect(page.getByRole('dialog')).toBeHidden()
    await expect(page.locator('.detail-panel .panel-heading')).toContainText('运行中', { timeout: 20_000 })
    if (action === '重载此版本') await expect(page.locator('.detail-panel .panel-heading')).toContainText(`代次 ${before + 1}`, { timeout: 20_000 })
  }
  await page.getByRole('button', { name: '重新读取配置', exact: true }).click()
  await expect(page.locator('.revision-bar strong').first()).toHaveText(String(oldRevision + 1))
  await expect(page.locator('.revision-bar strong').nth(1)).toHaveText(String(oldRevision + 1))
  await page.getByRole('navigation').getByRole('button', { name: /安全诊断/ }).click()
  await page.getByLabel('适配器插件', { exact: true }).selectOption('mock-adapter')
  await page.getByRole('button', { name: '查询状态', exact: true }).click()
  // The synthetic mock adapter deliberately lacks connection.status; errors must remain visible.
  await expect(page.locator('.adapter-error')).toBeVisible()
  await page.getByRole('button', { name: '↻ 刷新诊断', exact: true }).click()
  await expect(page.locator('.adapter-error')).toBeVisible()
  if (await page.getByLabel('适配器插件', { exact: true }).locator('option[value="adapter-snowluma"]').count()) {
    await page.getByLabel('适配器插件', { exact: true }).selectOption('adapter-snowluma')
    await page.getByRole('button', { name: '查询状态', exact: true }).click()
    await expect(page.locator('.diagnostic-json')).toContainText('"connected": false')
    await expect(page.locator('.adapter-error')).toBeHidden()
  }
  await expect(page.locator('.log-row').first()).toBeVisible()
  expect(errors).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: '退出登录 ↗' }).click()
  await expect(page.getByLabel('管理令牌', { exact: true })).toBeVisible()
})
